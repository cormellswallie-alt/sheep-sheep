'use strict';

const ICON_OL = '#5b3a1e';
const IconKit = (g) => {
  const K = {
    g,
    p() { g.beginPath(); return K; },
    c(x, y, r) { g.moveTo(x + r, y); g.arc(x, y, r, 0, Math.PI * 2); return K; },
    e(x, y, rx, ry, rot) { g.moveTo(x + rx * Math.cos(rot || 0), y + rx * Math.sin(rot || 0)); g.ellipse(x, y, rx, ry, rot || 0, 0, Math.PI * 2); return K; },
    m(x, y) { g.moveTo(x, y); return K; },
    l(x, y) { g.lineTo(x, y); return K; },
    q(a, b, x, y) { g.quadraticCurveTo(a, b, x, y); return K; },
    b(a, b, c, d, x, y) { g.bezierCurveTo(a, b, c, d, x, y); return K; },
    z() { g.closePath(); return K; },
    rr(x, y, w, h, r) { rr(g, x, y, w, h, r); return K; },
    lin(x0, y0, x1, y1, stops) { const gr = g.createLinearGradient(x0, y0, x1, y1); stops.forEach((s, i) => gr.addColorStop(i / (stops.length - 1), s)); return gr; },
    rad(x, y, r, stops) { const gr = g.createRadialGradient(x - r * 0.35, y - r * 0.4, r * 0.05, x, y, r); stops.forEach((s, i) => gr.addColorStop(i / (stops.length - 1), s)); return gr; },
    fill(f) { g.fillStyle = f; g.fill(); return K; },
    stroke(w, c) { g.lineWidth = w || 4.2; g.strokeStyle = c || ICON_OL; g.lineJoin = 'round'; g.lineCap = 'round'; g.stroke(); return K; },
    fs(f, w) { return K.fill(f).stroke(w); },
    shine(x, y, rx, ry, rot, a) { g.save(); g.globalAlpha = a || 0.7; K.p().e(x, y, rx, ry, rot || 0).fill('#fff'); g.restore(); return K; },
    line(pts, w, c) { K.p(); pts.forEach((pt, i) => (i ? g.lineTo(pt[0], pt[1]) : g.moveTo(pt[0], pt[1]))); return K.stroke(w, c); },
  };
  return K;
};

